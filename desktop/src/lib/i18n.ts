const messages: Record<AppLocale, Record<TranslationKey, string>> = {
  en: english,
  "zh-CN": chinese,
};

export function getStoredLocale(): LocalePreference {
  if (typeof window === "undefined") return "auto";
  try {
    const stored = window.localStorage.getItem("asvc.locale");
    return stored === "en" || stored === "zh-CN" || stored === "auto" ? stored : "auto";
  } catch {
    return "auto";
  }
}

export function saveLocale(preference: LocalePreference) {
  try {
    window.localStorage.setItem("asvc.locale", preference);
  } catch {
    // Local storage can be unavailable in restricted webviews; runtime state still works.
  }
}

export function resolveLocale(preference: LocalePreference): AppLocale {
  if (preference !== "auto") return preference;
  const language = typeof navigator === "undefined" ? "en" : navigator.language.toLowerCase();
  return language.startsWith("zh") ? "zh-CN" : "en";
}

export function translate(locale: AppLocale, key: TranslationKey, values: Record<string, string | number> = {}) {
  return messages[locale][key].replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? ""));
}

export type { TranslationKey };
